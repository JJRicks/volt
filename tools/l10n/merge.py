#!/usr/bin/env python3
"""Write a language's resource files from the council's decisions (plan 7.2 step 6).

  merge.py --tag es --area common          res/values-es/strings_common.xml
  merge.py --tag es --all                  every area with a decisions file
  merge.py --tag es --check                validate res/<folder>/ only; write nothing

For each key whose decision is translated (agreed, judged, safety-agreed or safety-judged) and whose source_sha1
still matches the English, it writes the string with a <!-- src:<sha1> --> comment (translib's
source hash). Keys that fall back, or whose English changed since the decision, are left out, so
Android shows English. The area that holds the default l10n_tag also gets
<string name="l10n_tag"><tag></string>. Only merge.py writes res/values-<qual>/.

Then it validates the whole folder (the CatalogCheckTest rules): every key exists in the default
with the same kind and is translatable; placeholders match; every plural category the language
needs is present; every sha comment matches the current English; ladders are complete; l10n_tag
names the language; the folder is listed in l10n/lang/; and aapt stores every text exactly as
written (when the SDK's aapt is available; --aapt off skips it, --aapt required fails without it).
"""

import argparse
import collections
import glob
import os
import re
import shutil
import subprocess
import sys
import tempfile

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_catalog  # noqa: E402
import l10nlib  # noqa: E402
import roundtrip  # noqa: E402
import translib  # noqa: E402

TRANSLATED = ("agreed", "judged", "safety-agreed", "safety-judged")
AAPT_VERSION = "36.1.0"
ANDROID_PLATFORM = "android-36"
SRC_COMMENT = re.compile(r"^src:([0-9a-f]{40})$")


def render_file(tag, area, lang, sources, decisions, tag_area):
    """(XML text, written keys, skipped [(key, why)])."""
    categories = translib.plural_categories(lang)
    lines = ['<?xml version="1.0" encoding="utf-8"?>',
             "<!-- Generated by tools/l10n/merge.py from l10n/decisions/%s/%s.jsonl. Do not edit by hand: change"
             % (tag, area),
             "     the decision and merge again. Each src comment is the hash of the English it translates. -->",
             "<resources>"]
    written, skipped = [], []
    if area == tag_area:
        lines.append('    <string name="%s">%s</string>' % (gen_catalog.TAG_KEY, translib.xml_text(tag)))
    for s in sources:
        d = decisions.get(s.key)
        if not s.translatable:
            continue
        if d is None:
            skipped.append((s.key, "no decision"))
            continue
        if d.get("outcome") not in TRANSLATED:
            skipped.append((s.key, "falls back to English"))
            continue
        sha = translib.source_sha1(s.kind, s.items)
        if d.get("source_sha1") != sha:
            skipped.append((s.key, "the English changed since the decision"))
            continue
        items = translib.items_of(s.kind, d.get("text"))
        if items is None:
            skipped.append((s.key, "the decision's text has the wrong shape"))
            continue
        formatted = "" if s.formatted else ' formatted="false"'
        lines.append("    <!-- src:%s -->" % sha)
        if s.kind == "string":
            lines.append('    <string name="%s"%s>%s</string>' % (
                s.key, formatted, translib.xml_text(translib.encode_resource_text(items["other"]))))
        else:
            missing = [q for q in categories if q not in items]
            if missing:
                lines.pop()
                skipped.append((s.key, "missing plural forms %s" % ", ".join(missing)))
                continue
            lines.append('    <plurals name="%s"%s>' % (s.key, formatted))
            for quantity in categories:
                lines.append('        <item quantity="%s">%s</item>' % (
                    quantity, translib.xml_text(translib.encode_resource_text(items[quantity]))))
            lines.append("    </plurals>")
        written.append(s.key)
    lines.append("</resources>")
    return "\n".join(lines) + "\n", written, skipped


def merge_area(paths, tag, area, sources=None, tag_area=None):
    lang = translib.load_language(paths, tag)
    if sources is None:
        sources, tag_area = translib.load_source(paths)
    if area not in sources:
        raise translib.L10nError("no res/values/strings_%s.xml" % area)
    decisions_path = paths.decisions(tag, area)
    if not os.path.exists(decisions_path):
        raise translib.L10nError("%s does not exist; run council.py decide first" % paths.rel(decisions_path))
    decisions = collections.OrderedDict((r.get("key"), r) for r in translib.read_jsonl(decisions_path))
    unknown = [k for k in decisions if k not in set(s.key for s in sources[area])]
    text, written, skipped = render_file(tag, area, lang, sources[area], decisions, tag_area)
    path = paths.res(lang.folder, "strings_%s.xml" % area)
    if written or area == tag_area:
        l10nlib.write_text(path, text)
    elif os.path.exists(path):
        os.remove(path)
    return path, written, skipped, unknown


