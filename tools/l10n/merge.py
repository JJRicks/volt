def validate_folder(paths, tag, aapt="auto"):
    """(problems, notes) for res/<folder>/ of one language."""
    lang = translib.load_language(paths, tag)
    languages = gen_catalog.load_languages(paths.lang_dir())
    problems, notes = [], []
    problems.extend(gen_catalog.check_text_folders(paths.res(), languages, paths.root))
    sources, tag_area = translib.load_source(paths)
    default = {}
    for rows in sources.values():
        for s in rows:
            default[s.key] = s
    by_area = dict((area, rows) for area, rows in sources.items())
    folder = paths.res(lang.folder)
    if not os.path.isdir(folder):
        return ["%s does not exist" % paths.rel(folder)], notes
    categories = translib.plural_categories(lang)
    seen, expected = {}, {}
    tag_value = None
    for filename in sorted(os.listdir(folder)):
        path = os.path.join(folder, filename)
        if not filename.endswith(".xml"):
            continue
        display = paths.rel(path)
        m = translib.AREA_FILE.match(filename)
        if not m:
            problems.append("%s: only strings_<area>.xml files belong in a language folder" % display)
            continue
        entries, file_problems = gen_catalog.read_strings_file(path, display)
        problems.extend(file_problems)
        area_keys = set(s.key for s in by_area.get(m.group(1), []))
        for e in entries:
            where = "%s:%d: %s" % (display, e.line, e.name)
            if e.name in seen:
                problems.append("%s: duplicate key (also in %s); aapt rejects it" % (where, seen[e.name]))
                continue
            seen[e.name] = display
            if e.name == gen_catalog.TAG_KEY:
                tag_value = e.items["other"].text if e.kind == "string" else None
                if tag_value != tag:
                    problems.append("%s: l10n_tag must be %r" % (where, tag))
                expected[(e.kind, e.name, "other")] = tag_value
                continue
            s = default.get(e.name)
            if s is None:
                problems.append("%s: not in the default catalog; English would crash without it" % where)
                continue
            if e.name not in area_keys:
                problems.append("%s: belongs in strings_%s.xml" % (where, s.area))
            if not s.translatable:
                problems.append("%s: translatable=\"false\" in the default" % where)
            if e.kind != s.kind:
                problems.append("%s: a %s; the default is a %s" % (where, e.kind, s.kind))
                continue
            if e.meta:
                problems.append("%s: volt:* metadata belongs only in res/values/" % where)
            if e.formatted != s.formatted:
                problems.append("%s: formatted=\"false\" must match the default" % where)
            sha = translib.source_sha1(s.kind, s.items)
            m_src = SRC_COMMENT.match((e.note or "").strip())
            if not m_src:
                problems.append("%s: no <!-- src:<sha1> --> comment" % where)
            elif m_src.group(1) != sha:
                problems.append("%s: stale: the English changed since this translation (src %s, now %s)" % (
                    where, m_src.group(1)[:12], sha[:12]))
            signature = translib.source_signature(s)
            if e.kind == "plural":
                missing = [q for q in categories if q not in e.items]
                if missing:
                    problems.append("%s: missing plural forms %s" % (where, ", ".join(missing)))
            for quantity, item in e.items.items():
                if s.formatted:
                    specs = set(_specs(item.text))
                    if e.kind == "string" and specs != set(_specs(s.items["other"])):
                        problems.append("%s: placeholders differ from the default" % where)
                    if not specs <= set(x for t in s.items.values() for x in _specs(t)):
                        problems.append("%s[%s]: placeholders the default does not have" % (where, quantity))
                    for index, conversion in item.args.items():
                        if signature.get(index) not in (None, conversion):
                            problems.append("%s: %%%d$ is %s in the default" % (where, index, signature[index]))
                expected[(e.kind, e.name, quantity)] = item.text
    for area, rows in sources.items():
        for base, members in translib.ladder_groups([s for s in rows if s.translatable]).items():
            present = [k for k in members if k in seen]
            if present and len(present) != len(members):
                problems.append("%s: ladder %s is partly translated (missing %s)" % (
                    paths.rel(folder), base, ", ".join(k for k in members if k not in seen)))
    if tag_value is None:
        if tag_area:
            notes.append("no l10n_tag yet: merge the %s area, or the app treats this folder as English" % tag_area)
        else:
            problems.append("the default catalog has no l10n_tag (B0b adds it), so the language cannot be detected")
    aapt_problems, aapt_note = run_aapt(paths, lang, expected, aapt)
    problems.extend(aapt_problems)
    if aapt_note:
        notes.append(aapt_note)
    return problems, notes


def _specs(text):
    return [m.group(0) for m in gen_catalog.PLACEHOLDER.finditer(text) if m.group(5) != "%"]


def find_aapt():
    sdk = os.environ.get("ANDROID_SDK_ROOT") or os.environ.get("ANDROID_HOME") or os.path.expanduser(
        "~/Library/Android/sdk")
    aapt = os.path.join(sdk, "build-tools", AAPT_VERSION, "aapt")
    jars = sorted(glob.glob(os.path.join(sdk, "platforms", ANDROID_PLATFORM, "android.jar")))
    if os.path.exists(aapt) and jars:
        return aapt, jars[-1]
    return None, None


def run_aapt(paths, lang, expected, mode="auto"):
    """Compile the default strings and this language's folder with aapt and compare what it stored."""
    if mode == "off":
        return [], "aapt check skipped (--aapt off)"
    aapt, android_jar = find_aapt()
    if not aapt:
        if mode == "required":
            return ["aapt %s or %s is not installed" % (AAPT_VERSION, ANDROID_PLATFORM)], None
        return [], "aapt not found: the aapt check runs in the local build instead"
    work = tempfile.mkdtemp(prefix="l10n-merge-")
    try:
        res = os.path.join(work, "res")
        os.makedirs(os.path.join(res, "values"))
        for path in glob.glob(paths.res("values", "strings*.xml")):
            shutil.copy(path, os.path.join(res, "values"))
        shutil.copytree(paths.res(lang.folder), os.path.join(res, lang.folder))
        manifest = os.path.join(work, "AndroidManifest.xml")
        l10nlib.write_text(manifest, '<?xml version="1.0" encoding="utf-8"?>\n<manifest xmlns:android='
                           '"http://schemas.android.com/apk/res/android" package="com.jjricks.volt.l10ncheck" />\n')
        apk = os.path.join(work, "check.apk")
        result = subprocess.run([aapt, "package", "-f", "-M", manifest, "-S", res, "-I", android_jar, "-F", apk],
                                stdout=subprocess.PIPE, stderr=subprocess.PIPE, timeout=300)
        if result.returncode != 0:
            message = result.stderr.decode("utf-8", "replace").replace(work + os.sep, "")
            return ["aapt rejected the folder:\n%s" % message.strip()], None
        config = lang.folder[len("values-"):]
        compiled = {}
        for entry in roundtrip.read_apk(apk):
            if entry.config != config:
                continue
            if entry.type_name == "string" and entry.value is not None:
                compiled[("string", entry.name, "other")] = entry.value
            elif entry.type_name == "plurals":
                for quantity, value in (entry.bag or {}).items():
                    compiled[("plural", entry.name, quantity)] = value
        problems = []
        for key, text in sorted(expected.items()):
            value = compiled.get(key)
            if value is None:
                problems.append("aapt: %s/%s[%s] is missing from configuration %s" % (key[0], key[1], key[2], config))
            elif value.styled or value.text != text:
                problems.append("aapt stored %s/%s[%s] as %s, not %r" % (key[0], key[1], key[2], value.describe(), text))
        return problems, "aapt %s compiled %d texts in %s exactly" % (AAPT_VERSION, len(expected), config) \
            if not problems else None
    finally:
        shutil.rmtree(work, ignore_errors=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--root")
    parser.add_argument("--tag", required=True)
    group = parser.add_mutually_exclusive_group(required=True)
    group.add_argument("--area")
    group.add_argument("--all", action="store_true")
    group.add_argument("--check", action="store_true", help="validate only")
    parser.add_argument("--aapt", choices=("auto", "off", "required"), default="auto")
    args = parser.parse_args(argv)
    paths = translib.Paths(args.root)
    try:
        translib.check_tag_area(args.tag, args.area)
        if not args.check:
            sources, tag_area = translib.load_source(paths)
            if args.all:
                directory = os.path.dirname(paths.decisions(args.tag, "x"))
                areas = sorted(f[:-6] for f in os.listdir(directory) if f.endswith(".jsonl")) \
                    if os.path.isdir(directory) else []
            else:
                areas = [args.area]
            for area in areas:
                path, written, skipped, unknown = merge_area(paths, args.tag, area, sources, tag_area)
                print("%s: %d translated, %d English" % (paths.rel(path), len(written), len(skipped)))
                for key, why in skipped:
                    print("  %s: %s" % (key, why))
                for key in unknown:
                    print("  %s: decided but no longer in the English; dropped" % key)
        problems, notes = validate_folder(paths, args.tag, args.aapt)
    except (translib.L10nError, gen_catalog.CatalogError) as error:
        print("merge.py: %s" % error, file=sys.stderr)
        return 2
    for note in notes:
        print("note: %s" % note)
    for problem in problems:
        print("problem: %s" % problem)
    print("validation: %s" % ("FAIL" if problems else "ok"))
    return 1 if problems else 0


if __name__ == "__main__":
    sys.exit(main())
