#!/usr/bin/env python3
"""Generates res/raw/tz_coords.txt for night vision's sunset schedule (ride-display plan, PR 3).

When the rider hasn't agreed to use the last ride's area, or no ride was recorded with location, Volt
works out sunset from the time zone's reference city. Android has no API for that, so Volt bundles
this table: one "Zone latitude longitude" line per zone, rounded to 0.1 degree, from tzdata's
zone1970.tab (or the older zone.tab), plus tzdata's links (backward names such as US/Mountain), read
from tzdata.zi ("L target link" lines) or the "backward" file.

  python3 tools/riding/tz_coords.py --tab /usr/share/zoneinfo/zone.tab \
      --links /usr/share/zoneinfo/tzdata.zi > res/raw/tz_coords.txt

Nothing is fetched: point it at a tzdata copy already on the machine. The output is sorted, so a new
tzdata release shows up as a plain diff.
"""

import argparse
import re
import sys

COORD = re.compile(r"^([+-])(\d{2})(\d{2})(\d{2})?([+-])(\d{3})(\d{2})(\d{2})?$")


def degrees(sign, d, m, s):
    value = int(d) + int(m) / 60 + (int(s) if s else 0) / 3600
    return -value if sign == "-" else value


def parse_coordinates(text):
    """ISO 6709 +DDMM+DDDMM or +DDMMSS+DDDMMSS to (latitude, longitude)."""
    m = COORD.match(text)
    if not m:
        raise ValueError("bad coordinates: " + text)
    return degrees(*m.group(1, 2, 3, 4)), degrees(*m.group(5, 6, 7, 8))


def read_tab(lines):
    zones = {}
    for line in lines:
        if not line.strip() or line.startswith("#"):
            continue
        fields = line.rstrip("\n").split("\t")
        if len(fields) < 3:
            continue
        zones[fields[2]] = parse_coordinates(fields[1])
    return zones


def read_links(lines):
    """(target, link) pairs from tzdata.zi "L target link" lines or the backward file's "Link target link"."""
    links = []
    for line in lines:
        fields = line.split("#", 1)[0].split()
        if len(fields) >= 3 and fields[0] in ("L", "Link"):
            links.append((fields[1], fields[2]))
    return links


def table(zones, links, version):
    rows = dict(zones)
    for target, link in links:
        if target in zones and link not in rows:
            rows[link] = zones[target]
    out = ["# Night vision's time-zone places: zone, latitude, longitude (0.1 degree).",
           "# Generated by tools/riding/tz_coords.py from tzdata " + version + "; do not edit by hand."]
    for zone in sorted(rows):
        latitude, longitude = rows[zone]
        out.append("%s %.1f %.1f" % (zone, round(latitude, 1) + 0.0, round(longitude, 1) + 0.0))
    return "\n".join(out) + "\n"


def tz_version(lines):
    for line in lines[:5]:
        m = re.match(r"#\s*version\s+(\S+)", line)
        if m:
            return m.group(1)
    return "(unknown version)"


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    parser.add_argument("--tab", required=True, help="zone1970.tab or zone.tab")
    parser.add_argument("--links", help="tzdata.zi or backward, for the links")
    parser.add_argument("--version", help="tzdata version for the header (read from tzdata.zi when omitted)")
    args = parser.parse_args(argv)
    with open(args.tab, encoding="utf-8") as f:
        zones = read_tab(f)
    links, version = [], args.version
    if args.links:
        with open(args.links, encoding="utf-8") as f:
            link_lines = f.readlines()
        links = read_links(link_lines)
        version = version or tz_version(link_lines)
    sys.stdout.write(table(zones, links, version or "(unknown version)"))
    return 0


if __name__ == "__main__":
    sys.exit(main())
